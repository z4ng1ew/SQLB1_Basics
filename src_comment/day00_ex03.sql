## DESC — сокращение от DESCENDING

**DESCENDING** (англ.) — «нисходящий», «убывающий»

---

## Оба варианта сортировки:

| Ключевое слово | Полная форма | Значение | Пример |
|----------------|--------------|----------|--------|
| `ASC` | ASCENDING | По возрастанию | 1, 2, 3, 4, 5 |
| `DESC` | DESCENDING | По убыванию | 5, 4, 3, 2, 1 |

---

## Примеры:

```sql
ORDER BY rating ASC   -- 2.3, 3.2, 4.2, 4.3, 4.6, 4.9
ORDER BY rating DESC  -- 4.9, 4.6, 4.3, 4.2, 3.2, 2.3

ORDER BY name ASC     -- Anna, Andrey, Denis... (А → Я)
ORDER BY name DESC    -- Peter, Nataly, Kate... (Я → А)
```

---

## По умолчанию:

Если не указать направление, SQL использует `ASC`:

```sql
ORDER BY rating       -- то же самое, что ORDER BY rating ASC
```