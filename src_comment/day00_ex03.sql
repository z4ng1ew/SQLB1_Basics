## Разбор SQL-запроса (Задание 03)

```sql
SELECT DISTINCT person_id
FROM person_visits
WHERE visit_date BETWEEN '2022-01-06' AND '2022-01-09'
   OR pizzeria_id = 2
ORDER BY person_id DESC;
```

---

## Построчное объяснение:

| Часть | Значение |
|-------|----------|
| `SELECT DISTINCT` | Выбрать уникальные значения (без дубликатов) |
| `person_id` | Столбец с идентификатором человека |
| `FROM person_visits` | Из таблицы посещений |
| `WHERE` | Начало условий фильтрации |
| `visit_date BETWEEN '2022-01-06' AND '2022-01-09'` | Дата посещения с 6 по 9 января включительно |
| `OR pizzeria_id = 2` | ИЛИ посещение пиццерии с id = 2 |
| `ORDER BY person_id DESC` | Сортировка по убыванию |

---

## Ключевые элементы:

**`DISTINCT`** — убирает дубликаты из результата:
```sql
SELECT person_id        → может вернуть: 1, 1, 2, 2, 3
SELECT DISTINCT person_id → вернёт: 1, 2, 3
```

**`OR`** — логическое «ИЛИ» (достаточно одного истинного условия):
```sql
условие_1 OR условие_2
-- строка попадёт в результат, если выполнится ХОТЯ БЫ ОДНО условие
```

**`DESC`** — сортировка по убыванию (от большего к меньшему):
```sql
ORDER BY person_id ASC   → 1, 2, 3, 4... (по умолчанию)
ORDER BY person_id DESC  → 9, 8, 7, 6...
```

**Формат даты** — в PostgreSQL даты пишутся в кавычках:
```sql
'2022-01-06'  -- формат: ГГГГ-ММ-ДД
```

---

## Логика выполнения:

1. Берём таблицу `person_visits`
2. Фильтруем: дата 6–9 января **ИЛИ** пиццерия с id = 2
3. Убираем дубликаты `person_id`
4. Сортируем по убыванию

