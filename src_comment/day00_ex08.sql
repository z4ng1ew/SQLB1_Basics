SELECT *
FROM person_order
WHERE id % 2 = 0
ORDER BY id;





Это решение 8-го упражнения. Всё просто:

**`id % 2 = 0`** — это проверка на чётность. Знак `%` называется **остаток от деления**:

```
1 % 2 = 1  → нечётное  ❌
2 % 2 = 0  → чётное    ✅
3 % 2 = 1  → нечётное  ❌
4 % 2 = 0  → чётное    ✅
5 % 2 = 1  → нечётное  ❌
6 % 2 = 0  → чётное    ✅
```

Если остаток от деления на 2 равен 0 — число чётное.

