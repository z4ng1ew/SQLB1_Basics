SELECT
    (SELECT name
     FROM person p
     WHERE p.id = pv.person_id) AS person_name,

    (SELECT name
     FROM pizzeria p
     WHERE p.id = pv.pizzeria_id) AS pizzeria_name
FROM
    (SELECT *
     FROM person_visits pv
     WHERE visit_date BETWEEN '2022-01-07' AND '2022-01-09') AS pv
ORDER BY 1 ASC,
         2 DESC;




Задание просит тебя написать запрос в **3 слоя**:

---

**Слой 1 — внутри FROM:**
```sql
-- сначала отфильтруй таблицу person_visits
-- оставь только визиты с 7 по 9 января
FROM (SELECT * FROM person_visits WHERE visit_date ...) AS pv
```
> *"Дай мне только нужные визиты"*

---

**Слой 2 — внутри SELECT:**
```sql
-- для каждого визита найди имя человека в таблице person
(SELECT name FROM person WHERE ...) AS person_name

-- для каждого визита найди название пиццерии в таблице pizzeria
(SELECT name FROM pizzeria WHERE ...) AS pizzeria_name
```
> *"Для каждого визита — найди кто пришёл и куда пришёл"*

---

**Слой 3 — сортировка:**
```sql
-- имена людей А→Я
-- названия пиццерий Я→А
ORDER BY person_name ASC, pizzeria_name DESC
```

---

**Итого простыми словами:**

> *"Покажи мне кто и куда ходил с 7 по 9 января, отсортируй людей от А до Я, а пиццерии от Я до А"*

---

По сути ты уже решил это в предыдущем запросе! Это и было 9-е упражнение 😊









```
ASC  → ASCENDING  → по возрастанию  (А→Я, 1→9)
DESC → DESCENDING → по убыванию     (Я→А, 9→1)
```

---

**Цифры 1 и 2 — это номера колонок в твоём SELECT:**

```sql
SELECT
    (...) AS person_name,   -- это колонка №1
    (...) AS pizzeria_name  -- это колонка №2
```

```sql
ORDER BY 1 ASC,   -- сортируй по колонке №1 (person_name) от А до Я
         2 DESC;  -- сортируй по колонке №2 (pizzeria_name) от Я до А
```

То есть вместо цифр можно написать названия — результат одинаковый:

```sql
ORDER BY person_name ASC,    -- то же самое что ORDER BY 1 ASC
         pizzeria_name DESC; -- то же самое что ORDER BY 2 DESC
```

Цифры — просто **сокращение** чтобы не писать длинные названия колонок.





















**Да, строки совпадают!** Каждая строка — это один визит:

```
Denis   → DinoPizza   -- Денис ходил в DinoPizza
Denis   → Best Pizza  -- Денис ходил в Best Pizza
Dmitriy → Papa Johns  -- Дмитрий ходил в Papa Johns
```

Всё правильно понимаешь — каждая строка показывает **кто и куда ходил**.

---

**Насчёт сортировки — да, это требование задания:**

> *"Добавь сортировку по имени человека в порядке возрастания и по названию пиццерии в порядке убывания"*

Поэтому:
```
person_name  → ASC  (А→Я) -- требование задания
pizzeria_name → DESC (Я→А) -- требование задания
```

---

**Почему такой странный порядок сортировки?** Посмотри на результат:

```
Denis   → DinoPizza   -- D раньше чем B... подожди
Denis   → Best Pizza  -- 
```

Сначала сортируется по имени А→Я (Denis, Denis, Dmitriy...), а если имена одинаковые — тогда пиццерия сортируется Я→А (DinoPizza перед Best Pizza, потому что D > B).

Это просто **учебное задание** чтобы ты попрактиковался с двойной сортировкой в разных направлениях. В реальности такую сортировку назначает бизнес-логика.