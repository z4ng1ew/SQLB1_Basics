SELECT name, age FROM person WHERE address = 'Kazan';


## Построчное объяснение:

| Часть | Значение |
|-------|----------|
| `SELECT` | Указывает, какие данные хотим получить |
| `name, age` | Выбираем два столбца: имя и возраст |
| `FROM person` | Из какой таблицы берём данные |
| `WHERE address = 'Kazan'` | Условие фильтрации: только те строки, где адрес равен 'Kazan' |

## Логика выполнения:

1. Берём таблицу `person` (9 записей)
2. Фильтруем: оставляем только строки, где `address = 'Kazan'`
3. Из отфильтрованных строк выводим только `name` и `age`

## Результат:

```
  name  | age
--------+-----
 Kate   |  33
 Denis  |  13
 Elvira |  45
```

