## SQL — интерпретируемый или компилируемый?

**Ни то, ни другое в классическом смысле.** SQL — это **декларативный язык запросов**.

Как он работает:

1. Ты пишешь запрос
2. **Парсер** проверяет синтаксис
3. **Оптимизатор** строит план выполнения (как лучше получить данные)
4. **Исполнитель** выполняет этот план

SQL не компилируется в машинный код и не интерпретируется построчно. Вместо этого СУБД (PostgreSQL) сама решает, *как* выполнить твой запрос наиболее эффективно.

Ты говоришь **что** хочешь получить, а база данных решает **как** это сделать.