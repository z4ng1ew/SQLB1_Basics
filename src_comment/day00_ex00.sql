## Почему порядок выполнения отличается от записи?

Это особенность SQL — **порядок написания** и **порядок выполнения** разные.

**Порядок написания (синтаксис):**
```sql
SELECT → FROM → WHERE
```

**Порядок выполнения (логика):**
```sql
FROM → WHERE → SELECT
```

## Почему так?

Это логично, если подумать:

1. **FROM** — сначала нужно понять, *откуда* брать данные
2. **WHERE** — затем *отфильтровать* нужные строки
3. **SELECT** — и только потом *выбрать* столбцы из отфильтрованного

Нельзя выбрать столбцы, пока не знаешь таблицу. Нельзя фильтровать, пока не определил источник.

## Аналогия:

Представь, что ты ищешь книгу:
1. Идёшь в библиотеку (**FROM**)
2. Ищешь книги определённого автора (**WHERE**)
3. Берёшь только название и год издания (**SELECT**)

