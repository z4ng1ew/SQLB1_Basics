## Разбор SQL-запроса (Задание 04)

```sql
SELECT concat(name, ' (age:', age::varchar, ',gender:''', gender, ''',address:''', address, ''')') AS person_information
FROM person
ORDER BY person_information;
```

---

## Построчное объяснение:

| Часть | Значение |
|-------|----------|
| `SELECT` | Выбираем данные |
| `concat(...)` | Функция склеивания строк |
| `AS person_information` | Псевдоним (имя) для результирующего столбца |
| `FROM person` | Из таблицы person |
| `ORDER BY person_information` | Сортировка по вычисляемому полю |

---

## Разбор функции concat:

```sql
concat(name, ' (age:', age::varchar, ',gender:''', gender, ''',address:''', address, ''')')
```

**`concat()`** — склеивает все аргументы в одну строку:

| Аргумент | Пример значения |
|----------|-----------------|
| `name` | Anna |
| `' (age:'` | (age: |
| `age::varchar` | 16 |
| `',gender:'''` | ,gender:' |
| `gender` | female |
| `''',address:'''` | ',address:' |
| `address` | Moscow |
| `''')'` | ') |

---

## Ключевые элементы синтаксиса:

**`age::varchar`** — приведение типа (casting):
```sql
age::varchar  -- число 16 превращается в строку '16'
```
Нужно потому, что `concat` работает со строками, а `age` — это число.

**`''`** — экранирование одинарной кавычки:
```sql
''''     -- одна кавычка внутри строки
''''''   -- две кавычки внутри строки

-- Пример:
',gender:'''  -- даёт строку:  ,gender:'
```

Правило: чтобы вставить `'` внутрь строки, пишем `''`.

---

## Как формируется результат:

Для Anna (16, female, Moscow):

```
Anna + ' (age:' + '16' + ',gender:'' + 'female' + '',address:'' + 'Moscow' + '')'
```

Результат:
```
Anna (age:16,gender:'female',address:'Moscow')
```

---

## Альтернативный синтаксис (оператор ||):

```sql
SELECT name || ' (age:' || age::varchar || ',gender:''' || gender || ''',address:''' || address || ''')' AS person_information
FROM person
ORDER BY person_information;
```

**`||`** — оператор конкатенации (склеивания) строк, делает то же самое, что `concat()`.

---

## Результат:

```
             person_information
---------------------------------------------
 Andrey (age:21,gender:'male',address:'Moscow')
 Anna (age:16,gender:'female',address:'Moscow')
 Denis (age:13,gender:'male',address:'Kazan')
 ...
```


























## VARCHAR — что это?

**VARCHAR** — сокращение от **VAR**iable **CHAR**acter (переменный символ)

Это тип данных для хранения **текстовых строк переменной длины**.

---

## Типы данных в SQL:

| Тип | Описание | Пример |
|-----|----------|--------|
| `INTEGER` | Целые числа | 1, 42, -100 |
| `NUMERIC` | Числа с дробной частью | 3.14, 4.9 |
| `VARCHAR` | Текст (строка) | 'Anna', 'Kazan' |
| `DATE` | Дата | '2022-01-07' |
| `BOOLEAN` | Логический | true, false |

---

## Зачем нужно `age::varchar`?

В запросе `age` — это число (`INTEGER`), а функция `concat()` склеивает строки.

```sql
age::varchar  -- преобразует число в строку
```

| До | После |
|----|-------|
| `16` (число) | `'16'` (строка) |

---

## Синтаксис приведения типов в PostgreSQL:

```sql
-- Способ 1: двойное двоеточие
age::varchar

-- Способ 2: функция CAST
CAST(age AS varchar)
```

Оба варианта делают одно и то же — преобразуют значение из одного типа в другой.




















## Приведение типов — что это?

**Приведение типов** — это преобразование данных из одного типа в другой.

---

## Простая аналогия:

Представь, что у тебя есть число **16** и ты хочешь написать его в предложении:

```
Мне 16 лет.
```

Для компьютера:
- `16` — это число (можно складывать, умножать)
- `'16'` — это текст (можно склеивать с другим текстом)

Приведение типов — это когда ты говоришь: «возьми число 16 и сделай из него текст '16'».

---

## Пример в SQL:

```sql
-- Число
SELECT 16 + 4;           -- Результат: 20 (математика)

-- Строка
SELECT '16' || '4';      -- Результат: '164' (склеивание)

-- Приведение типа
SELECT 16::varchar;      -- Число 16 → строка '16'
SELECT '16'::integer;    -- Строка '16' → число 16
```

---

## Зачем это нужно?

В задании 04 мы склеиваем строку:

```sql
concat(name, ' (age:', age, ...
```

| Переменная | Тип | Значение |
|------------|-----|----------|
| `name` | varchar | 'Anna' |
| `age` | integer | 16 |

Нельзя просто склеить текст с числом — нужно сначала превратить число в текст:

```sql
age::varchar   -- 16 → '16'
```

---

## Синтаксис в PostgreSQL:

```sql
значение::новый_тип

-- Примеры:
age::varchar        -- число → строка
'3.14'::numeric     -- строка → число
'2022-01-07'::date  -- строка → дата
```
















## Разбор функции concat()

**`concat()`** — это функция, которая склеивает несколько частей в одну строку.

---

## Простой пример:

```sql
SELECT concat('Привет', ' ', 'мир');
```

Результат:
```
Привет мир
```

Функция взяла три части и склеила их вместе.

---

## Как это работает в задании:

```sql
concat(name, ' (age:', age::varchar)
```

| Аргумент | Значение |
|----------|----------|
| `name` | Anna |
| `' (age:'` | (age: |
| `age::varchar` | 16 |

Результат склеивания:
```
Anna (age:16
```

---

## Аналогия:

Представь, что ты собираешь бусы на нитку:

```
[Anna] + [ (age:] + [16] = [Anna (age:16]
```

Каждый аргумент в `concat()` — это одна бусина. Функция нанизывает их по порядку.

---

## Синтаксис:

```sql
concat(часть1, часть2, часть3, ...)
```

- Аргументы перечисляются через запятую
- Можно передать сколько угодно аргументов
- Всё склеивается в одну строку

---

## Полный пример из задания:

```sql
concat(name, ' (age:', age::varchar, ',gender:''', gender, ''')')
```

Пошагово для Anna:

| Шаг | Добавляем | Результат |
|-----|-----------|-----------|
| 1 | `name` = Anna | Anna |
| 2 | `' (age:'` | Anna (age: |
| 3 | `age::varchar` = 16 | Anna (age:16 |
| 4 | `',gender:'''` | Anna (age:16,gender:' |
| 5 | `gender` = female | Anna (age:16,gender:'female |
| 6 | `''')'` | Anna (age:16,gender:'female') |











## Разбор: `age:', age::varchar, '`

Это **три отдельных аргумента** в функции `concat()`, разделённые запятыми:

---

## Разбивка:

```sql
concat(..., 'age:', age::varchar, ',gender:', ...)
```

| № | Аргумент | Что это | Значение |
|---|----------|---------|----------|
| 1 | `'age:'` | Просто текст | age: |
| 2 | `age::varchar` | Значение из таблицы, преобразованное в строку | 16 |
| 3 | `',gender:'` | Просто текст | ,gender: |

---

## Визуально:

```
'age:'  ,  age::varchar  ,  ',gender:'
  ↓            ↓               ↓
текст      переменная        текст
  ↓            ↓               ↓
"age:"    →   "16"    →   ",gender:"
```

Результат склеивания:
```
age:16,gender:
```

---

## Главное правило:

- **В кавычках** `'...'` — это обычный текст (пишется как есть)
- **Без кавычек** — это переменная (берётся значение из таблицы)

```sql
'age:'        -- текст "age:" (всегда одинаковый)
age           -- столбец таблицы (разный для каждой строки: 16, 21, 33...)
age::varchar  -- то же самое, но преобразованное в текст
```

---

## Аналогия:

Как в обычном языке программирования:

```python
# Python
name = "Anna"
age = 16
print("Имя: " + name + ", возраст: " + str(age))
#      ↑ текст  ↑ переменная  ↑ текст    ↑ переменная
```

В SQL:
```sql
concat('Имя: ', name, ', возраст: ', age::varchar)
--      ↑ текст  ↑ переменная  ↑ текст    ↑ переменная
```




































## Разбор: `'''` — экранирование кавычек

В SQL строки пишутся в одинарных кавычках: `'текст'`

Но что если нужно вставить **саму кавычку** внутрь строки?

---

## Правило:

Чтобы вставить одну кавычку `'` внутрь строки, пишем **две кавычки** `''`

---

## Разбор `'''`:

```
' ' '
↑ ↑ ↑
│ │ └── закрывающая кавычка строки
│ └──── сама кавычка (экранированная)
└────── открывающая кавычка строки
```

| Запись | Результат |
|--------|-----------|
| `''''` | одна кавычка: `'` |
| `''''''` | две кавычки: `''` |

---

## Пример:

```sql
SELECT 'Hello';       -- Результат: Hello
SELECT 'It''s me';    -- Результат: It's me
SELECT '''Hi''';      -- Результат: 'Hi'
```

---

## В твоём запросе:

```sql
',gender:'''
```

Разбираем:

| Часть | Что это |
|-------|---------|
| `'` | открытие строки |
| `,gender:` | обычный текст |
| `''` | экранированная кавычка → `'` |
| `'` | закрытие строки |

Результат: `,gender:'`

---

## Полная картина:

```sql
concat(..., ',gender:''', gender, ''',address:''', ...)
```

| Аргумент | Результат |
|----------|-----------|
| `',gender:'''` | ,gender:' |
| `gender` | female |
| `''',address:'''` | ',address:' |

Склеивается в:
```
,gender:'female',address:'
```

---

## Почему так сложно?

Задание требует вывести строку с кавычками внутри:

```
Anna (age:16,gender:'female',address:'Moscow')
                    ↑      ↑         ↑      ↑
                    эти кавычки — часть результата
```

Поэтому приходится экранировать их через `''`.




























## Разбор: `AS person_information`

**`AS`** — задаёт **псевдоним** (имя) для столбца в результате.

---

## Зачем это нужно?

Без `AS`:

```sql
SELECT concat(name, ' (age:', age::varchar, ')') FROM person;
```

Результат:

```
                concat
-------------------------------
 Anna (age:16)
 Andrey (age:21)
```

Столбец называется `concat` — некрасиво и непонятно.

---

С `AS`:

```sql
SELECT concat(name, ' (age:', age::varchar, ')') AS person_information FROM person;
```

Результат:

```
       person_information
-------------------------------
 Anna (age:16)
 Andrey (age:21)
```

Столбец называется `person_information` — понятно и читаемо.

---

## Синтаксис:

```sql
выражение AS имя_столбца
```

---

## Примеры:

```sql
SELECT name AS имя FROM person;
SELECT age AS возраст FROM person;
SELECT age + 10 AS age_plus_ten FROM person;
SELECT concat(name, '!') AS greeting FROM person;
```

---

## Важно для задания:

В задании требуется, чтобы столбец назывался именно `person_information`:

```sql
... AS person_information
```

А потом по этому имени можно сортировать:

```sql
ORDER BY person_information
```






















FROM person говорит: «Все эти столбцы бери из таблицы person».







## Разбор: `FROM person`

**`FROM person`** — указывает, **откуда брать данные** для запроса.

---

## В контексте твоего запроса:

```sql
SELECT concat(name, ' (age:', age::varchar, ',gender:''', gender, ''',address:''', address, ''')') AS person_information
FROM person
ORDER BY person_information;
```

Ты используешь переменные: `name`, `age`, `gender`, `address`

Но откуда SQL знает, что такое `name`? Где искать `age`?

**`FROM person`** говорит: «Все эти столбцы бери из таблицы `person`».

---

## Таблица person:

| id | name | age | gender | address |
|----|------|-----|--------|---------|
| 1 | Anna | 16 | female | Moscow |
| 2 | Andrey | 21 | male | Moscow |
| 3 | Kate | 33 | female | Kazan |
| ... | ... | ... | ... | ... |

Когда пишешь `name` в запросе — SQL берёт значения из столбца `name` этой таблицы.

---

## Аналогия:

```sql
SELECT name FROM person;
```

Как на обычном языке:
```
ВЫБЕРИ имя ИЗ таблицы_людей;
```

Без `FROM person` SQL не поймёт, откуда брать `name` — в базе может быть много таблиц с таким столбцом.

---

## Что будет без FROM?

```sql
SELECT concat(name, ' (age:', age::varchar, ')');
-- ОШИБКА: column "name" does not exist
```

SQL не знает, где искать `name`.