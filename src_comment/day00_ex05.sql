--   ## Зачем нужны подзапросы?

-- **Подзапрос** — это запрос внутри другого запроса. Он нужен, чтобы **получить данные из связанных таблиц**.

-- ---

-- ## Проблема:

-- У тебя есть две таблицы:

-- **person_order** (заказы):
-- | id | person_id | menu_id | order_date |
-- |----|-----------|---------|------------|
-- | 8 | 4 | 18 | 2022-01-07 |

-- **person** (люди):
-- | id | name | age |
-- |----|------|-----|
-- | 4 | Denis | 13 |

-- В `person_order` есть только `person_id = 4`, но нет имени. Имя хранится в другой таблице.

-- ---

-- ## Задача:

-- Показать **имя** человека, который сделал заказ. Но имя в одной таблице, а заказ в другой.

-- ---

-- ## Решение — подзапрос:

-- ```sql
-- SELECT
--     (SELECT name FROM person p WHERE p.id = po.person_id) AS name
-- FROM person_order po
-- WHERE menu_id = 18;
-- ```

-- Логика:
-- 1. Берём заказ с `menu_id = 18` → видим `person_id = 4`
-- 2. Подзапрос идёт в таблицу `person` и ищет `id = 4`
-- 3. Находит имя `Denis`
-- 4. Возвращает его в результат

-- ---

-- ## Практический смысл:

-- | Ситуация | Подзапрос помогает |
-- |----------|-------------------|
-- | Данные в разных таблицах | Связать их и получить нужное |
-- | Нужна агрегация | Посчитать сумму/среднее внутри запроса |
-- | Фильтрация по условию из другой таблицы | Найти «все заказы клиентов из Казани» |

-- ---

-- ## Аналогия из жизни:

-- Ты в библиотеке. У тебя есть **номер читательского билета** (это как `person_id`).

-- Чтобы узнать **имя читателя**, нужно:
-- 1. Взять номер билета
-- 2. Пойти в картотеку (другая таблица)
-- 3. Найти карточку с этим номером
-- 4. Прочитать имя

-- Подзапрос делает именно это автоматически.

-- ---

-- ## Альтернатива — JOIN:

-- Обычно для связывания таблиц используют `JOIN`:

