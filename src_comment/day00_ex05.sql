│  2 │     3     │         │  3 │ Anna   │
└────┴───────────┘         └────┴────────┘
      po.person_id    ==    p.id
```

Такой подзапрос называется **коррелированным** — он выполняется отдельно для каждой строки внешнего запроса, используя её данные.












