## Разбор SQL-запросов (Задание 02)

Два запроса делают одно и то же, но разным синтаксисом.

---

## Запрос 1: Операторы сравнения

```
SELECT name, 
       rating
FROM pizzeria
WHERE rating >= 3.5
  AND rating <= 5
ORDER BY rating;
```

**Разбор:**

| Часть | Значение |
|-------|----------|
| `SELECT name, rating` | Выбираем столбцы: название и рейтинг |
| `FROM pizzeria` | Из таблицы пиццерий |
| `WHERE rating >= 3.5` | Рейтинг больше или равен 3.5 |
| `AND rating <= 5` | И одновременно меньше или равен 5 |
| `ORDER BY rating` | Сортировка по рейтингу (по возрастанию) |

**Операторы сравнения:**

| Оператор | Значение |
|----------|----------|
| `>=` | больше или равно |
| `<=` | меньше или равно |
| `AND` | логическое «И» (оба условия должны быть истинны) |

---

## Запрос 2: Оператор BETWEEN или ключевое слово 

```sql
SELECT name, 
       rating
FROM pizzeria
WHERE rating BETWEEN 3.5 AND 5
ORDER BY rating;
```

**Разбор:**

| Часть | Значение |
|-------|----------|
| `BETWEEN 3.5 AND 5` | Значение в диапазоне от 3.5 до 5 включительно |

---

## Сравнение двух подходов:

| Подход | Запись | Включает границы? |
|--------|--------|-------------------|
| Операторы | `rating >= 3.5 AND rating <= 5` | Да |
| BETWEEN | `rating BETWEEN 3.5 AND 5` | Да |

**BETWEEN** — это сокращённая запись для `>= AND <=`. Оба варианта эквивалентны.

---

